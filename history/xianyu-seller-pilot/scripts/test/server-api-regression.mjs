import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const { createDatabase } = require('../../server/db/database.js')
const { createAuthService } = require('../../server/auth/auth-service.js')
const { buildHttpApp } = require('../../server/http/app.js')

async function main() {
  const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'xianyu-server-api-'))
  const filename = path.join(tempDir, 'server.sqlite')
  const first = createDatabase({ filename })
  assert.equal(first.schemaVersion(), 9)
  const auth = createAuthService({ db: first })
  const admin = auth.createUser({ username: 'admin', password: 'DEMO_ONLY_REDACTED', displayName: 'Admin', role: 'admin' })
  const operator = auth.createUser({ username: 'operator', password: 'DEMO_ONLY_REDACTED', displayName: 'Operator', role: 'operator' })
  const readOnly = auth.createUser({ username: 'viewer', password: 'DEMO_ONLY_REDACTED', displayName: 'Viewer', role: 'read_only' })
  first.upsertBrowserProfile({ id: 'profile-1', provider: 'fake', vendorProfileId: 'fixture-1', label: 'Fixture profile', userDataDir: '/srv/private/profile-1', createdBy: admin.id })
  const pending = first.createJob({ type: 'browser_probe', payload: { url: 'https://example.test' }, profileId: 'profile-1', operatorId: operator.id })
  assert.equal(first.getJob(pending.id).status, 'pending')
  first.close()

  const reopened = createDatabase({ filename })
  assert.equal(reopened.schemaVersion(), 9)
  assert.equal(reopened.getBrowserProfile('profile-1').vendor_profile_id, 'fixture-1')
  assert.equal(reopened.getJob(pending.id).payload.url, 'https://example.test')
  const dueSchedule = reopened.createSchedule({ name: 'Due fixture', jobType: 'browser_probe', payload: { url: 'https://example.test/scheduled' }, profileId: 'profile-1', createdBy: operator.id, intervalMs: 1000, nextRunAt: new Date(Date.now() - 1000).toISOString() })
  const scheduled = reopened.enqueueDueSchedules(new Date())
  assert.equal(scheduled.length, 1)
  assert.equal(scheduled[0].schedule.id, dueSchedule.id)
  const reopenedAuth = createAuthService({ db: reopened })
  const app = buildHttpApp({ db: reopened, auth: reopenedAuth, config: { provider: 'fake', dataDir: tempDir } })
  await app.fastify.ready()

  const login = async (username, password) => {
    const response = await app.fastify.inject({ method: 'POST', url: '/auth/login', payload: { username, password } })
    assert.equal(response.statusCode, 200)
    const cookieHeader = response.headers['set-cookie']
    const cookie = Array.isArray(cookieHeader) ? cookieHeader[0] : cookieHeader
    assert.match(String(cookie), /^sid=/)
    return cookie.split(';')[0]
  }
  const adminCookie = await login('admin', 'admin-pass-123')
  const operatorCookie = await login('operator', 'operator-pass-123')
  const viewerCookie = await login('viewer', 'viewer-pass-123')
  const profilesResponse = await app.fastify.inject({ method: 'GET', url: '/profiles', headers: { cookie: viewerCookie } })
  assert.equal(profilesResponse.statusCode, 200)
  assert.equal(profilesResponse.json().profiles[0].vendor_profile_id, 'fixture-1')
  assert.equal(Object.hasOwn(profilesResponse.json().profiles[0], 'user_data_dir'), false)
  const profileCreate = await app.fastify.inject({ method: 'POST', url: '/profiles', headers: { cookie: operatorCookie }, payload: { provider: 'camoufox', vendorProfileId: 'camoufox-1', label: 'Camoufox fixture' } })
  assert.equal(profileCreate.statusCode, 201)
  const profileId = profileCreate.json().profile.id
  const profileUpdate = await app.fastify.inject({ method: 'PATCH', url: `/profiles/${profileId}`, headers: { cookie: operatorCookie }, payload: { name: 'Renamed Profile', enabled: false } })
  assert.equal(profileUpdate.statusCode, 200)
  assert.equal(profileUpdate.json().profile.label, 'Renamed Profile')
  assert.equal(profileUpdate.json().profile.status, 'disabled')
  const productionApp = buildHttpApp({ db: reopened, auth: reopenedAuth, config: { provider: 'camoufox', environment: 'production', dataDir: tempDir } })
  await productionApp.fastify.ready()
  const productionMismatch = await productionApp.fastify.inject({ method: 'POST', url: '/profiles', headers: { cookie: operatorCookie }, payload: { provider: 'adspower', vendorProfileId: 'adspower-mismatch', label: 'Should be rejected' } })
  assert.equal(productionMismatch.statusCode, 409)
  assert.equal(productionMismatch.json().error.code, 'provider_mismatch')
  await productionApp.fastify.close()

  const unauthenticated = await app.fastify.inject({ method: 'GET', url: '/jobs' })
  assert.equal(unauthenticated.statusCode, 401)
  const csrfRejected = await app.fastify.inject({ method: 'POST', url: '/jobs', headers: { cookie: operatorCookie, origin: 'https://evil.example', host: 'localhost' }, payload: { type: 'browser_probe', payload: {} } })
  assert.equal(csrfRejected.statusCode, 403)
  const viewerCreate = await app.fastify.inject({ method: 'POST', url: '/jobs', headers: { cookie: viewerCookie }, payload: { type: 'browser_probe', payload: {} } })
  assert.equal(viewerCreate.statusCode, 403)
  const operatorCreate = await app.fastify.inject({ method: 'POST', url: '/jobs', headers: { cookie: operatorCookie }, payload: { type: 'market_snapshot', profileId: 'profile-1', payload: { query: 'monitor' } } })
  assert.equal(operatorCreate.statusCode, 201)
  const created = operatorCreate.json().job
  assert.equal(created.operator_id, operator.id)
  assert.equal(Object.hasOwn(created, 'lease_token'), false)
  assert.equal(Object.hasOwn(created, 'worker_id'), false)
  assert.equal(Object.hasOwn(created, 'lease_expires_at'), false)
  assert.equal(Object.hasOwn(created, 'retry_at'), false)
  const createdEvent = reopened.listEvents({ after: 0 }).at(-1)
  assert.equal(createdEvent.eventType, 'job.created')
  assert.equal(createdEvent.jobType, 'market_snapshot', 'event ledger must expose the job type for H5 lifecycle mapping')
  const activeSummary = await app.fastify.inject({ method: 'GET', url: '/jobs/active-summary', headers: { cookie: viewerCookie } })
  assert.equal(activeSummary.statusCode, 200)
  assert.equal(activeSummary.json().counts.market_snapshot.pending, 1, 'H5 must receive aggregate active-job counts instead of a capped job list')
  assert.ok(Number.isInteger(activeSummary.json().eventCursor))
  const viewerCancel = await app.fastify.inject({ method: 'POST', url: `/jobs/${created.id}/cancel`, headers: { cookie: viewerCookie }, payload: {} })
  assert.equal(viewerCancel.statusCode, 403)
  const paused = await app.fastify.inject({ method: 'POST', url: `/tasks/${created.id}/control`, headers: { cookie: operatorCookie, 'content-type': 'application/json' }, payload: { command: 'pause' } })
  assert.equal(paused.statusCode, 200)
  assert.equal(paused.json().task.control_requested, 'pause')
  const resumed = await app.fastify.inject({ method: 'POST', url: `/tasks/${created.id}/control`, headers: { cookie: operatorCookie, 'content-type': 'application/json' }, payload: { command: 'resume' } })
  assert.equal(resumed.statusCode, 200)
  assert.equal(resumed.json().task.control_requested, null)
  const cancelled = await app.fastify.inject({ method: 'POST', url: `/jobs/${created.id}/cancel`, headers: { cookie: operatorCookie }, payload: {} })
  assert.equal(cancelled.statusCode, 200)
  assert.equal(cancelled.json().job.status, 'cancelled')

  const events = await app.fastify.inject({ method: 'GET', url: '/events?after=0', headers: { cookie: adminCookie, accept: 'text/event-stream' } })
  assert.equal(events.statusCode, 200)
  assert.match(events.headers['content-type'], /text\/event-stream/)
  assert.match(events.body, /event: job.created/)
  assert.match(events.body, /event: job.cancelled/)
  assert.match(events.body, /"jobType":"market_snapshot"/)
  const nextCursor = Number(events.headers['x-events-next-cursor'])
  const replay = await app.fastify.inject({ method: 'GET', url: `/events?after=${nextCursor}`, headers: { cookie: adminCookie } })
  assert.equal(replay.statusCode, 200)
  assert.match(replay.body, /heartbeat/)

  const claimed = reopened.claimJob({ workerId: 'worker-1', leaseToken: 'DEMO_ONLY_REDACTED' })
  assert.ok(claimed)
  assert.equal(claimed.status, 'running')
  const completed = reopened.completeJob({ jobId: claimed.id, workerId: 'worker-1', leaseToken: 'DEMO_ONLY_REDACTED', result: { ok: true } })
  assert.equal(completed.status, 'succeeded')
  assert.equal(reopened.listEvents({ after: nextCursor }).at(-1).eventType, 'job.succeeded')
  const workerEvents = await app.fastify.inject({ method: 'GET', url: `/events?after=${nextCursor}`, headers: { cookie: adminCookie, accept: 'text/event-stream' } })
  assert.equal(workerEvents.statusCode, 200)
  assert.equal(workerEvents.body.includes('worker-1'), false)
  assert.equal(workerEvents.body.includes('leaseExpiresAt'), false)
  const workerEventsViaLastId = await app.fastify.inject({ method: 'GET', url: '/events', headers: { cookie: adminCookie, accept: 'text/event-stream', 'last-event-id': String(nextCursor) } })
  assert.equal(workerEventsViaLastId.statusCode, 200)
  assert.match(workerEventsViaLastId.body, /event: job\.succeeded/)

  const adminUsers = await app.fastify.inject({ method: 'POST', url: '/auth/users', headers: { cookie: adminCookie }, payload: { username: 'newop', password: 'DEMO_ONLY_REDACTED', role: 'operator' } })
  assert.equal(adminUsers.statusCode, 201)
  const operatorUsers = await app.fastify.inject({ method: 'POST', url: '/auth/users', headers: { cookie: operatorCookie }, payload: { username: 'badop', password: 'DEMO_ONLY_REDACTED', role: 'operator' } })
  assert.equal(operatorUsers.statusCode, 403)
  const scheduleResponse = await app.fastify.inject({ method: 'POST', url: '/schedules', headers: { cookie: operatorCookie }, payload: { name: 'API schedule', jobType: 'browser_probe', profileId: 'profile-1', intervalMs: 1000, nextRunAt: new Date(Date.now() + 60_000).toISOString(), payload: { url: 'https://example.test/scheduled-api' } } })
  assert.equal(scheduleResponse.statusCode, 201)
  assert.equal((await app.fastify.inject({ method: 'GET', url: '/schedules', headers: { cookie: viewerCookie } })).statusCode, 200)
  assert.equal(JSON.stringify(events.body).includes('api-key'), false)

  await app.fastify.close()
  reopened.close()
  fs.rmSync(tempDir, { recursive: true, force: true })
  console.log(`server-api-regression: PASS (${reopened.listEvents ? 'auth/db/events' : 'ok'})`)
}

main().catch(error => {
  console.error(error)
  process.exitCode = 1
})
