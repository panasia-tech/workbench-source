  getState: () => ipcRenderer.invoke("get-state"),
  refreshDevices: () => ipcRenderer.invoke("refresh-devices"),
  openScreen: (serial) => ipcRenderer.invoke("open-screen", serial),
  closeScreen: (serial) => ipcRenderer.invoke("close-screen", serial),
  tileScreens: () => ipcRenderer.invoke("tile-screens"),
  setAutoTile: (on) => ipcRenderer.invoke("set-autotile", on),
  revive: (serial) => ipcRenderer.invoke("revive", serial),
  installApp: (serial) => ipcRenderer.invoke("install-app", serial),
  initDevice: (serial) => ipcRenderer.invoke("init-device", serial),
  setAutoPerm: (on) => ipcRenderer.invoke("set-autoperm", on),
  fixPerms: () => ipcRenderer.invoke("fix-perms"),
  checkAppUpdate: () => ipcRenderer.invoke("check-app-update"),
  downloadAppUpdate: () => ipcRenderer.invoke("download-app-update"),
  checkXianyu: () => ipcRenderer.invoke("check-xianyu"),
  downloadXianyu: () => ipcRenderer.invoke("download-xianyu"),
