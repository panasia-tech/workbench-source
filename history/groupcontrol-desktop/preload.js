  adsDoctor: () => ipcRenderer.invoke("ads-doctor"),
  adsStart: (uids) => ipcRenderer.invoke("ads-start", uids),
  adsStop: (uids, withBrowser) => ipcRenderer.invoke("ads-stop", uids, withBrowser),
